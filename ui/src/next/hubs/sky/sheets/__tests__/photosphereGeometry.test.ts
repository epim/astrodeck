test('Overlap check catches inverted or misregistered textured frames without changing the panorama',()=>{
  const w=160,h=120,basis=lookBasis(0,25),data=scene(basis,w,h);
  const p=new SkyPanorama(720,201);p.add(data,w,h,basis);
  assert.equal(p.checkOverlap(data,w,h,basis).result,'agree');
  const exposure=data.map((v,i)=>i%4===3?v:Math.min(255,v*.65+12));
  assert.equal(p.checkOverlap(exposure,w,h,basis).result,'agree','Exposure alone is not misalignment');
  const inverted=new Uint8ClampedArray(data.length);
  for(let i=0;i<w*h;i++)inverted.set(data.subarray(i*4,i*4+4),(w*h-1-i)*4);
  const before=p.pixels.slice();
  assert.equal(p.checkOverlap(inverted,w,h,basis).result,'conflict');
  assert.deepEqual(p.pixels,before,'A rejected image changed the mosaic');
  const moved=lookBasis(12,30);
  assert.equal(p.checkOverlap(scene(moved,w,h),w,h,moved).result,'agree','Correctly projected overlap rejected');
});

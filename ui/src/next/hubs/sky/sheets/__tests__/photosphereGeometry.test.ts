function scene(basis:CameraBasis,width=160,height=120):Uint8ClampedArray {
  const data=new Uint8ClampedArray(width*height*4),lens=cameraLens(width,height);
  for(let y=0;y<height;y++)for(let x=0;x<width;x++){
    const sx=((x+.5)/width*2-1)*lens.tanX,sy=(1-(y+.5)/height*2)*lens.tanY;
    const ray=unit(basis.forward.map((v,i)=>v+basis.right[i]*sx+basis.up[i]*sy) as V3);
    const {az,alt}=skyAngles(ray),top=az>30&&az<90?75:az>180&&az<240?35:8;
    const color=alt<=top?[25,45,30,255]:[100,175,240,255];data.set(color,(y*width+x)*4);
  }
  return data;
}

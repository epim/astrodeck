  assert.equal(p.checkOverlap(inverted,w,h,basis).result,'conflict');
  assert.deepEqual(p.pixels,before,'A rejected image changed the mosaic');
  const moved=lookBasis(12,30);
  assert.equal(p.checkOverlap(scene(moved,w,h),w,h,moved).result,'agree','Correctly projected overlap rejected');

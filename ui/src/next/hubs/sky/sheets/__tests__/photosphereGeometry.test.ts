test('Known image landmarks land at their bearings and heights, including both sides of north',()=>{
  const w=240,h=320,data=new Uint8ClampedArray(w*h*4).fill(40);
  // Portrait short axis = horizontal 60 degrees. Independent pinhole formula.
  const focal=w/(2*Math.tan(Math.PI/6));
  const marks=[{az:0,alt:0,rgb:[255,0,0]},{az:15,alt:0,rgb:[0,255,0]},{az:0,alt:20,rgb:[0,0,255]}];
  for(const mark of marks){
    const a=mark.az*Math.PI/180,b=mark.alt*Math.PI/180;
    const x=w/2+focal*Math.tan(a),y=h/2-focal*Math.tan(b)/Math.cos(a);
    for(let yy=Math.round(y)-4;yy<=Math.round(y)+4;yy++)for(let xx=Math.round(x)-4;xx<=Math.round(x)+4;xx++)data.set([...mark.rgb,255],(yy*w+xx)*4);
  }
  const panorama=new SkyPanorama(720,301);
  panorama.add(data,w,h,orientationBasis(0,90,0));
  const pixel=(az:number,alt:number)=>{
    const x=Math.floor(((az+360)%360)/360*720),y=Math.round((90-alt)*3);
    return [...panorama.pixels.slice((y*720+x)*4,(y*720+x)*4+3)];
  };
  for(const mark of marks)assert.deepEqual(pixel(mark.az,mark.alt),mark.rgb);
  assert.deepEqual(pixel(359.5,0),[255,0,0]);
  assert.deepEqual(pixel(.5,0),[255,0,0]);
});

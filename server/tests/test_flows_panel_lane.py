class TestTheWorkedCases:
    """Spec 1.5's four worked cases, a branched lane, a mid-lane pass wire and
    a flow cycle with no way in, each graded on its owners, its lane, its tail,
    its loop and its compile.

    Mutant "owner is any upstream TARGET" (the doctor's set walk: collect every
    node upstream along flow wires, through any type, and return the nearest
    TARGET or POOL) failed all three on dome-ends-the-lane, and only there:
        AssertionError: dome-ends-the-lane: ha
        assert 't' == None
        AssertionError: dome-ends-the-lane: t
        {'lane': ['cy', 'ha']} != {'lane': ['cy']}
        {'tail': 'ha'} != {'tail': 'cy'}
        AssertionError: dome-ends-the-lane
        assert {'t': [['cy', 'ha']]} == {'t': [['cy']]}

    The same three tests caught these, one line of each failure quoted:
        "no seen-set" [flow-cycle-with-no-way-in]:
            AssertionError: owner_of('a') did not return within 5 s
            AssertionError: the lane of 't' did not return within 5 s
        "legacy rule in mosaic graphs" [second-target-owns-the-capture]:
            {'m31': [['cy', 'ha']]} != {'m31': [['cy']]}
        "the tail is the deepest stage, branched or not" [branched-lane]:
            {'tail': 'ha'} != {'tail': None}
        "any pass wire from the lane into next" [mid-lane-pass-wire]:
            {'loop': True} != {'loop': False}
        "wire kinds ignored" [af-guide-cycle]:
            {'next': ['t', 'r']} != {'next': ['r']}
        "any node can be walked from" [af-guide-cycle]:
            {'tail': 'r'} != {'tail': 'cy'}
        "no scope notes" [second-target-owns-the-capture]:
            assert [] == ['ha']
        "a note for every scoped stage" [af-guide-cycle]:
            assert ['cy'] == []
    """

    @pytest.mark.parametrize("case", CASES, ids=lambda c: c["id"])
    def test_owner_of_every_lane_node(self, case):
        g = _graph(case)
        for nid, want in case["owners"].items():
            got = _bounded(lambda: _id(owner_of(g, nid)), f"owner_of({nid!r})")
            assert got == want, f"{case['id']}: {nid}"

    @pytest.mark.parametrize("case", CASES, ids=lambda c: c["id"])
    def test_the_lane_its_tail_and_its_loop(self, case):
        g = _graph(case)
        for oid, want in case["lanes"].items():
            owner = g.node(oid)
            got = _bounded(lambda: {
                "lane": [n.id for n in panel_lane(g, owner)],
                "tail": _id(lane_tail(g, owner)),
                "branched": lane_branched(g, owner),
                "loop": bool(loop_wires(g, owner)),
                "next": [n.id for n in lane_next(g, owner)],
            }, f"the lane of {oid!r}")
            assert got == want, f"{case['id']}: {oid}"

    @pytest.mark.parametrize("case", CASES, ids=lambda c: c["id"])
    def test_the_compile_scopes_every_stage(self, case):
        plan = _bounded(lambda: compile_plan(_graph(case), "n"), "compile_plan")
        want = {oid: [ids] for oid, ids in case["compile"]["steps"].items()}
        assert _steps_by_block(plan) == want, case["id"]
        assert [x["node_id"] for x in plan.get("notes", [])] == \
            case["compile"]["notes"], case["id"]

    def test_the_fixture_holds_the_cases_the_spec_names(self):
        """S3-U grades its mirror against this file, so a case quietly dropped
        here is a case dropped from both languages.

        Mutant of the FIXTURE (a scratch copy) "drop branched-lane" failed:
            AssertionError: assert {'af-guide-cy...-the-capture'} >=
            {'af-guide-cy...-the-capture'}
              Extra items in the right set:
              'branched-lane'
        """
        assert {c["id"] for c in CASES} >= {
            "af-guide-cycle", "cycle-then-capture",
            "second-target-owns-the-capture", "dome-ends-the-lane",
            "branched-lane", "mid-lane-pass-wire"}



class TestTheLaneShape:

    def test_a_branched_lane_has_no_tail(self):
        """AF feeds both CYCLE and CAPTURE Ha: two last stages. Choosing one
        would put the loop wire on a stage the operator did not mean (M12).

        Mutant "the tail is the deepest stage, branched or not" failed:
            AssertionError: assert 'ha' is None
        """
        g = _graph(_case("branched-lane"))
        t = g.node("t")
        assert lane_branched(g, t) is True
        assert _id(lane_tail(g, t)) is None

    def test_fan_out_from_the_target_itself_is_a_branch(self):
        """Spec 1.5 item 4: "no fan-out from the TARGET or between lane nodes".

        Mutant "the tail is the deepest stage, branched or not" failed:
            AssertionError: assert FlowNode(id='c', type='capture', x=200.0,
            y=100.0, params={}) is None
        """
        g = FlowGraph(
            nodes=[_n("t", "target", rows=3, cols=2),
                   _n("cy", "cycle", x=200), _n("c", "capture", x=200, y=100)],
            edges=[_e("t", "target", "cy", "run"), _e("t", "target", "c", "run")])
        assert lane_branched(g, g.node("t")) is True
        assert lane_tail(g, g.node("t")) is None

    def test_a_non_lane_sibling_is_not_a_branch(self):
        """Control: TARGET feeds a CYCLE and a DOME. DOME is not a lane node,
        so the lane is still one chain and its tail is the CYCLE.

        Mutant "any node can be walked from" (DOME joins the lane) failed:
            AssertionError: assert True is False
        """
        g = FlowGraph(
            nodes=[_n("t", "target", rows=3, cols=2),
                   _n("cy", "cycle", x=200), _n("dm", "dome", x=200, y=100)],
            edges=[_e("t", "target", "cy", "run"), _e("t", "target", "dm", "run")])
        assert lane_branched(g, g.node("t")) is False
        assert _id(lane_tail(g, g.node("t"))) == "cy"

    def test_an_empty_lane(self):
        """A TARGET wired straight to a REPORT owns nothing: no tail, no loop,
        and nothing to call branched.

        Mutant "any node can be walked from" failed:
            AssertionError: assert ([FlowNode(id=...0, params={})] == []
              Left contains one more item: FlowNode(id='r', type='report',
              x=100.0, y=0.0, params={})
        """
        g = FlowGraph(nodes=[_n("t", "target", rows=3, cols=2), _n("r", "report", x=100)],
                      edges=[_e("t", "target", "r", "session")])
        t = g.node("t")
        assert panel_lane(g, t) == [] and lane_tail(g, t) is None
        assert lane_branched(g, t) is False and loop_wires(g, t) == []

    def test_what_runs_next_names_each_node_once_in_canvas_order(self):
        """The tail's 'all done' wired twice to one REPORT (a duplicate a
        half-built graph can hold) is still one thing that runs next, and two
        different next nodes read in canvas order, as the compile walks them.

        Mutant "lane_next keeps duplicate wires" failed:
            AssertionError: assert ['dm', 'r', 'r'] == ['dm', 'r']
              Left contains one more item: 'r'
        Mutant "lane_next in wire order" failed:
            AssertionError: assert ['r', 'dm'] == ['dm', 'r']
        """
        g = FlowGraph(
            nodes=[_n("t", "target", rows=3, cols=2), _n("cy", "cycle", x=200),
                   _n("r", "report", x=600), _n("dm", "dome", x=400, y=200)],
            edges=[_e("t", "target", "cy", "run"),
                   _e("cy", "complete", "r", "session", "w1"),
                   _e("cy", "complete", "r", "session", "w2"),
                   _e("cy", "complete", "dm", "run", "w3")])
        assert [n.id for n in lane_next(g, g.node("t"))] == ["dm", "r"]



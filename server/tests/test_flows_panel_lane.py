"""The panel lane: which TARGET a capture or cycle stage belongs to (#151,
#189 U-09 part; spec 2026-09-23 flows mosaic, 1.3 item 1, 1.4 items 1-4, 1.5
and D2).

WHY THIS EXISTS. The compile used to hand every CAPTURE LOOP and FILTER CYCLE
to every target seen earlier in canvas order. For a mosaic that leaks: a
CAPTURE drawn after a second TARGET would be shot on all six M31 panels as
well. So in a graph with a multi-panel block, a stage belongs only to the
TARGET (or POOL) its flow wires lead back to through lane nodes, found by
``owner_of``, and the loop wire is the ``pass`` wire from the lane's tail into
that block's ``next``.

THE WORKED CASES live in ``fixtures/panel_lane_cases.json``, written from the
spec's table rather than generated by the code they grade, because the
TypeScript mirror (S3-U) grades itself against the same file. The named
mutants below were each run in a private scratch copy of ``server/``, never in
the shared tree (#254), and the failure each one produced is quoted verbatim
in the test that caught it.
"""
from __future__ import annotations

import ctypes
import json
import threading
from pathlib import Path

import pytest

from astrodeck.flows.compile import (
    compile_plan,
    is_multi_panel,
    lane_branched,
    lane_next,
    lane_tail,
    loop_wires,
    owner_of,
    panel_lane,
)
from astrodeck.flows.models import FlowEdge, FlowGraph, FlowNode

FIXTURE = Path(__file__).parent / "fixtures" / "panel_lane_cases.json"
CASES = json.loads(FIXTURE.read_text(encoding="utf-8"))["cases"]


def _case(case_id: str) -> dict:
    return next(c for c in CASES if c["id"] == case_id)


def _graph(case: dict) -> FlowGraph:
    return FlowGraph.model_validate(case["graph"])


def _n(nid, ntype, x=0.0, y=0.0, **params):
    return FlowNode(id=nid, type=ntype, x=x, y=y, params=params)


def _e(a, ap, b, bp, eid=None):
    kw = {"from": a, "fromPort": ap, "to": b, "toPort": bp}
    if eid is not None:
        kw["id"] = eid
    return FlowEdge(**kw)


def _steps_by_block(plan: dict) -> dict[str, list[list[str]]]:
    """Each block's compiled entries, as the stage node ids each one carries.
    A list per block, because a POOL emits one entry per member."""
    out: dict[str, list[list[str]]] = {}
    for t in plan["targets"]:
        out.setdefault(t["node_id"], []).append([s["node_id"] for s in t["steps"]])
    return out


def _id(node):
    return None if node is None else node.id


class _Runaway(BaseException):
    """Raised INTO a walk that overran its bound, to stop it."""


def _bounded(fn, what: str, timeout: float = 5.0):
    """``fn()``, run in a daemon thread and given ``timeout`` seconds.

    Every walk in this file goes through here because one fixture case is a
    flow cycle: without the seen-set a walk goes round it for ever, and a
    test that hangs is a test nobody reads. Bounded, the mutant FAILS with a
    sentence instead.

    THE OVERRUNNING THREAD IS STOPPED, not abandoned. Measured under the "no
    seen-set" mutant: two abandoned threads still spinning took three tests
    to 48 s and the file past 300 s, because every GIL release on the main
    thread (the conftest teardown's ctypes calls release it hundreds of times)
    then waits out a spinning thread's switch interval. So an overrun gets
    ``_Runaway`` raised inside it, which a pure-Python loop meets at its next
    bytecode check."""
    box: dict = {}

    def run():
        try:
            box["value"] = fn()
        except BaseException as exc:        # re-raised on the test's thread
            box["error"] = exc

    th = threading.Thread(target=run, daemon=True)
    th.start()
    th.join(timeout)
    if th.is_alive():
        ctypes.pythonapi.PyThreadState_SetAsyncExc(
            ctypes.c_ulong(th.ident), ctypes.py_object(_Runaway))
        th.join(timeout)
    assert "value" in box or "error" in box, \
        f"{what} did not return within {timeout:g} s"
    if isinstance(box.get("error"), _Runaway):
        raise AssertionError(f"{what} did not return within {timeout:g} s")
    if "error" in box:
        raise box["error"]
    return box["value"]



class TestScopingInTheCompile:

    def test_the_capture_after_a_second_target_stays_off_the_mosaic(self):
        """Worked case 3. Under the canvas-order rule the CAPTURE after
        TARGET(M33) is appended to every target seen so far, M31 included, so
        six M31 panels would each owe it.

        Mutant "legacy rule in mosaic graphs" failed:
            AssertionError: assert ['cy', 'ha'] == ['cy']
        """
        plan = compile_plan(_graph(_case("second-target-owns-the-capture")), "n")
        by = {t["node_id"]: [s["node_id"] for s in t["steps"]] for t in plan["targets"]}
        assert by["m31"] == ["cy"]
        assert by["m33"] == ["ha"]

    def test_a_two_lane_flow_with_a_mosaic_scopes_by_wire(self):
        """Two separate lanes, laid out so canvas order interleaves them: the
        mosaic's TARGET, the single TARGET, then each one's stage. By canvas
        order both stages would reach both targets.

        Mutant "legacy rule in mosaic graphs" failed:
            AssertionError: assert {'a': [['cy',...[['cy', 'c']]} ==
            {'a': [['cy']], 'b': [['c']]}
              {'a': [['cy', 'c']]} != {'a': [['cy']]}
              {'b': [['cy', 'c']]} != {'b': [['c']]}
        """
        g = FlowGraph(
            nodes=[_n("a", "target", x=100, name="M31", rows=2, cols=2),
                   _n("b", "target", x=200, y=300, name="M33"),
                   _n("cy", "cycle", x=300, plan="L 60, R 60"),
                   _n("c", "capture", x=400, y=300, filter="Ha", count=10)],
            edges=[_e("a", "target", "cy", "run"), _e("b", "target", "c", "run"),
                   _e("cy", "pass", "a", "next")])
        assert _steps_by_block(compile_plan(g, "n")) == {
            "a": [["cy"]], "b": [["c"]]}

    def test_every_pool_member_gets_its_own_lanes_stage_only(self):
        """A POOL lane beside a mosaic: both members carry the pool's CAPTURE,
        in their own dicts, and none of the mosaic's CYCLE.

        Mutant "legacy rule in mosaic graphs" failed:
            {'t': [['cy', 'c']]} != {'t': [['cy']]}
            {'p': [['cy', 'c'], ['cy', 'c']]} != {'p': [['c'], ['c']]}
        Mutant "POOL is not an owner" failed:
            AssertionError: assert {'p': [[], []], 't': [['cy']]} ==
            {'p': [['c'],...'t': [['cy']]}
        """
        g = FlowGraph(
            nodes=[_n("t", "target", x=0, name="M31", rows=3, cols=2),
                   _n("p", "pool", x=100, y=300, members="A, B"),
                   _n("cy", "cycle", x=200, plan="L 60"),
                   _n("c", "capture", x=300, y=300, count=5)],
            edges=[_e("t", "target", "cy", "run"), _e("p", "target", "c", "run")])
        plan = compile_plan(g, "n")

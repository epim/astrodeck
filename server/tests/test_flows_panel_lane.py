class TestOwnerOfIsAChainWalk:

    def test_the_capture_after_the_dome_belongs_to_no_target(self):
        """TARGET -> CYCLE -> DOME -> CAPTURE. DOME ends the lane, so the
        CAPTURE belongs to nobody and must compile to nothing (M13 makes that
        loud). The doctor's set walk would find the TARGET upstream and hand
        the CAPTURE to all six panels, which is the leak this rule closes.

        Mutant "owner is any upstream TARGET" failed:
            AssertionError: assert 't' is None
        Mutant "legacy rule in mosaic graphs" failed:
            AssertionError: assert ['cy', 'ha'] == ['cy']
        """
        g = _graph(_case("dome-ends-the-lane"))
        assert _id(owner_of(g, "ha")) is None
        m31 = compile_plan(g, "n")["targets"][0]
        assert [s["node_id"] for s in m31["steps"]] == ["cy"]

    def test_a_legacy_slew_is_part_of_the_lane(self):
        """Every saved flow and every Example still draws SLEW + CENTER between
        the TARGET and its stages (it is legacy, not deleted, spec 1.7). If it
        ended the lane, every one of those stages would belong to no target.

        Mutant "SLEW is not a lane node" failed:
            AssertionError: assert None == 't'
        """
        g = FlowGraph(
            nodes=[_n("t", "target", rows=3, cols=2), _n("s", "slew", x=100),
                   _n("af", "autofocus", x=200), _n("g", "guide", x=300),
                   _n("c", "capture", x=400)],
            edges=[_e("t", "target", "s", "run"), _e("s", "centered", "af", "run"),
                   _e("af", "focused", "g", "run"), _e("g", "guiding", "c", "run")])
        assert _id(owner_of(g, "c")) == "t"

    def test_a_flow_cycle_does_not_hang_the_walk(self):
        """Two stages feed each other and nothing feeds them. Each has exactly
        one flow parent, so a walk with no memory of where it has been goes
        round for ever. Run in a thread and bounded, so the mutant FAILS
        rather than hanging the suite.

        Mutant "no seen-set" failed (the walk never returned):
            AssertionError: owner_of on a flow cycle did not return within 5 s
        """
        g = _graph(_case("flow-cycle-with-no-way-in"))
        got = _bounded(lambda: {"a": _id(owner_of(g, "a")),
                                "b": _id(owner_of(g, "b")),
                                "tail": _id(lane_tail(g, g.node("t")))},
                       "owner_of on a flow cycle")
        assert got == {"a": None, "b": None, "tail": None}

    def test_two_flow_parents_have_no_owner(self):
        """Only a graph built outside the editor has two wires into one flow
        input (validation refuses it), but the compile routes still compile
        half-built graphs. Two parents are two answers; picking one would hand
        the stage to a block by edge order, so there is no owner.

        Mutant "the first parent wins" failed, and so did "owner is any
        upstream TARGET":
            AssertionError: assert 'a' is None
        """
        g = FlowGraph(
            nodes=[_n("a", "target", rows=3, cols=2), _n("b", "target", y=100),
                   _n("c", "capture", x=200)],
            edges=[_e("a", "target", "c", "run"), _e("b", "target", "c", "run")])
        assert _id(owner_of(g, "c")) is None

    def test_the_same_parent_wired_twice_is_still_one_chain(self):
        """Control for the rule above: a duplicated wire from ONE parent names
        one block, so the owner is not ambiguous.

        Mutant "a parent wired twice is two parents" failed:
            AssertionError: assert None == 'a'
        """
        g = FlowGraph(
            nodes=[_n("a", "target", rows=3, cols=2), _n("c", "capture", x=200)],
            edges=[_e("a", "target", "c", "run", "w1"),
                   _e("a", "target", "c", "run", "w2")])
        assert _id(owner_of(g, "c")) == "a"

    def test_a_node_that_ends_the_lane_is_owned_by_nobody(self):
        """DOME, REPORT and a second TARGET are not lane nodes; asking who
        owns one is asking who owns a node outside every lane. Controls: none
        of them may be answered with the block above them.

        Mutant "any node can be walked from" failed:
            AssertionError: assert FlowNode(id='t', type='target', x=0.0,
            y=0.0, params={'name': 'M31', 'rows': 3, 'cols': 2}) is None
        """
        g = _graph(_case("dome-ends-the-lane"))
        assert owner_of(g, "dm") is None
        g3 = _graph(_case("second-target-owns-the-capture"))
        assert owner_of(g3, "m33") is None
        g1 = _graph(_case("af-guide-cycle"))
        assert owner_of(g1, "r") is None
        assert owner_of(g1, "no-such-node") is None

    def test_a_stage_under_a_pool_belongs_to_the_pool(self):
        """Mutant "POOL is not an owner" failed:
            AssertionError: assert None == 'p'
        """
        g = FlowGraph(
            nodes=[_n("p", "pool", members="A, B"), _n("g", "guide", x=100),
                   _n("c", "capture", x=200)],
            edges=[_e("p", "target", "g", "run"), _e("g", "guiding", "c", "run")])
        assert _id(owner_of(g, "c")) == "p"

    def test_the_loop_wire_is_not_a_step_of_the_cursor(self):
        """The loop wire points backwards from the tail into the TARGET. It is
        an event ("whenever a pass is done"), so reading it as a flow wire
        would make the TARGET a child of its own tail and list it as what
        runs after the mosaic.

        Mutant "wire kinds ignored" (every wire is a flow wire) failed:
            AssertionError: assert ['t', 'r'] == ['r']
        """
        g = _graph(_case("af-guide-cycle"))
        assert [n.id for n in lane_next(g, g.node("t"))] == ["r"]
        assert _id(owner_of(g, "cy")) == "t"

    def test_a_flow_output_dropped_on_next_is_not_a_step(self):
        """FILTER CYCLE 'all done' dropped on TARGET 'next panel' crosses the
        flow/event boundary, which validation refuses and a half-built graph
        can still hold. Read by its source port alone it would be a flow step
        into the TARGET, and the TARGET would run after its own lane.

        Mutant "a wire is a flow wire by its source port alone" failed:
            AssertionError: assert ['t'] == []
        """
        g = FlowGraph(
            nodes=[_n("t", "target", rows=3, cols=2), _n("cy", "cycle", x=200)],
            edges=[_e("t", "target", "cy", "run"),
                   _e("cy", "complete", "t", "next")])
        assert [n.id for n in lane_next(g, g.node("t"))] == []
        assert _id(owner_of(g, "cy")) == "t"



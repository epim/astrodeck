"""Generate the UI's TypeScript for the session report FROM THE SERVER MODELS.

    python tools/gen_report_types.py            # write ui/src/types.report.generated.ts
    python tools/gen_report_types.py --check    # exit 1 if that file is out of date

Why generated and not written by hand (#797): ``ui/src/types.ts`` carried a
hand-copied ``TargetBreakdown``, and the claim that a mirror test held it to
the server's model was false, so a field added to ``TargetBreakdown`` or
``FrameRecord`` could not turn anything red when the UI's copy lagged. The
file this writes is read out of ``astrodeck.sequence.report``'s pydantic
models, ``server/tests/test_w3_mosaic_identity.py`` fails when the committed
copy lags the models, and ``types.ts`` re-exports ``FilterBreakdown`` and
``TargetBreakdown`` from it, so a server-added field reaches the UI's types by
construction and a dropped or retyped one breaks ``tsc -b`` at its readers.

The shape is what ``GET /api/reports/{id}`` sends: every model field is a key,
an optional one is ``T | null``. A field the route withholds from a principal
without ``view.site_derived`` (``altitude_deg``, #567) is marked optional.
Nothing in the output is timestamped, so regenerating without changing a model
writes the same bytes and ``--check`` means something.
"""
from __future__ import annotations

import argparse
import sys
import types
import typing
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "server"))

from pydantic import BaseModel  # noqa: E402

from astrodeck.sequence import report  # noqa: E402

OUT = REPO / "ui" / "src" / "types.report.generated.ts"

#: The models to emit, in dependency order (a model comes after those it names).
MODELS: tuple[type[BaseModel], ...] = (
    report.FilterBreakdown,
    report.TargetBreakdown,
    report.FrameRecord,
    report.SessionReport,
)

#: Fields the report route withholds from a caller without
#: ``view.site_derived`` (#567), so the key may be absent on the wire. A test
#: holds this to ``redact._REPORT_ALTITUDE_KEY``.
WITHHELD: dict[str, tuple[str, ...]] = {"FrameRecord": ("altitude_deg",)}

_HEADER = """\
// Copyright (c) 2026 James Penick
// SPDX-License-Identifier: Apache-2.0
// GENERATED by tools/gen_report_types.py from server/astrodeck/sequence/report.py.
// Do not edit: change the model and run `python tools/gen_report_types.py`.
// A test fails when this file lags the model.
"""

_SCALARS = {str: "string", int: "number", float: "number", bool: "boolean",
            type(None): "null"}


class Unmapped(Exception):
    """A model field whose type this generator has no spelling for."""


def ts_type(tp: object) -> str:
    """The TypeScript spelling of one annotation."""
    if tp in _SCALARS:
        return _SCALARS[tp]
    if tp is typing.Any:
        return "unknown"
    if isinstance(tp, type) and issubclass(tp, BaseModel):
        return tp.__name__
    origin = typing.get_origin(tp)
    args = typing.get_args(tp)
    if origin in (typing.Union, types.UnionType):
        return " | ".join(dict.fromkeys(ts_type(a) for a in args))
    if origin is list:
        inner = ts_type(args[0])
        return f"({inner})[]" if " | " in inner else f"{inner}[]"
    if origin is dict:
        return f"Record<string, {ts_type(args[1])}>"
    if tp is dict:
        return "Record<string, unknown>"
    raise Unmapped(f"no TypeScript spelling for {tp!r}")


def interface(model: type[BaseModel]) -> str:
    """One model as an ``export interface``."""
    withheld = WITHHELD.get(model.__name__, ())
    lines = [f"export interface {model.__name__} {{"]
    for name, info in model.model_fields.items():
        mark = "?" if name in withheld else ""
        lines.append(f"  {name}{mark}: {ts_type(info.annotation)};")
    lines.append("}")
    return "\n".join(lines)


def render() -> str:
    """The whole generated file."""
    body = "\n\n".join(interface(m) for m in MODELS)
    return f"{_HEADER}\n{body}\n"


def write(path: Path = OUT) -> None:
    """Write the file with LF endings and no BOM, whatever the platform."""
    path.write_bytes(render().encode("utf-8"))


def stale(path: Path = OUT) -> bool:
    """True when the committed file is not what the models generate. Compared
    with line endings folded, because a git checkout may have made them CRLF."""
    try:
        have = path.read_bytes().decode("utf-8").replace("\r\n", "\n")
    except FileNotFoundError:
        return True
    return have != render()


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if the committed file is out of date")
    args = ap.parse_args(argv)
    if args.check:
        if stale():
            print(f"{OUT.relative_to(REPO)} is out of date: run "
                  f"python tools/gen_report_types.py", file=sys.stderr)
            return 1
        return 0
    write()
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
